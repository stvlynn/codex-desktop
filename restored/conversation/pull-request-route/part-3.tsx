function jadeite(journal, kingpin) {
  let land = new Map();
  for (let mesh of journal) {
    let neck = {
      owner: mesh.pullRequest.owner,
      repository: mesh.pullRequest.repository,
    };
    land.set(
      `${neck.owner.toLowerCase()}/${neck.repository.toLowerCase()}`,
      neck,
    );
  }
  return (
    kingpin != null &&
      land.set(
        `${kingpin.owner.toLowerCase()}/${kingpin.repository.toLowerCase()}`,
        kingpin,
      ),
    [...land.values()]
      .sort((pad, quillshaft) =>
        `${pad.owner}/${pad.repository}`.localeCompare(
          `${quillshaft.owner}/${quillshaft.repository}`,
        ),
      )
      .map((item) => ({
        label: `${item.owner}/${item.repository}`,
        repository: item,
      }))
  );
}
